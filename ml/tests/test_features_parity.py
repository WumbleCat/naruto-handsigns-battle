"""The Python feature extractor must match the TypeScript reference exactly.

The fixture is generated by src/detection/features.golden.test.ts (run with UPDATE_GOLDEN=1).
"""

import json
from pathlib import Path

import numpy as np
import pytest

from jutsu_ml.features import FEATURE_DIM, extract_features

GOLDEN = Path(__file__).parent / "fixtures" / "features-golden.json"


@pytest.fixture(scope="module")
def golden() -> dict:
    if not GOLDEN.exists():
        pytest.skip("golden file missing; run `UPDATE_GOLDEN=1 npm test -- features.golden` first")
    return json.loads(GOLDEN.read_text(encoding="utf-8"))


def test_feature_dim() -> None:
    assert FEATURE_DIM == 131


def test_matches_typescript_reference(golden: dict) -> None:
    assert golden["featureSpec"] == "hands-v1"
    assert len(golden["cases"]) > 0
    for case in golden["cases"]:
        actual = extract_features(case["hands"], case["aspect"])
        expected = np.array(case["features"], dtype=np.float32)
        assert actual.shape == expected.shape, case["name"]
        np.testing.assert_allclose(actual, expected, rtol=0, atol=1e-6, err_msg=case["name"])
